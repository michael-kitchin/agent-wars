"""Copy subdivision flag SVGs from the iso3166-flags release.

Wikimedia Commons rate-limits this client, so the files come from the MIT
dataset at https://github.com/amckenna41/iso3166-flags instead. A file over
300 KB, or a file that is not an SVG, is skipped. Missing codes fall back to
the national flag later.
"""

from __future__ import annotations

import io
import logging
import re
import ssl
import sys
import urllib.error
import urllib.request
import zipfile
from pathlib import Path

LOGGER = logging.getLogger(__name__)

# GitHub's certificate validates. The unverified context is only a fallback when the local store rejects it.
_SSL_CONTEXT = ssl.create_default_context()
_SSL_CONTEXT_INSECURE = ssl._create_unverified_context()

_USER_AGENT = "AgentWarsSubdivisionFlags/1.0 (local educational game; subdivision flag mirror)"
_RELEASE_ZIP = "https://github.com/amckenna41/iso3166-flags/releases/download/iso3166-flags/iso3166-flags.zip"
_SOURCE_LABEL = "https://github.com/amckenna41/iso3166-flags"
_MAX_BYTES = 300 * 1024
_CODE_PATTERN = re.compile(r"^[a-z0-9]{2}-[a-z0-9~]+$")
_REPO_ROOT = Path(__file__).resolve().parents[1]
_FLAG_DIR = _REPO_ROOT / "static" / "flags" / "subdivisions"
_ATTRIBUTION = _FLAG_DIR / "ATTRIBUTION.md"
_ALLOW_LIST = _REPO_ROOT / "src" / "shared" / "subdivisionFlagCodes.ts"
def _download_release_zip() -> bytes:
    """
    Why this exists:
        Commons is rate-limiting this client, so subdivision SVGs come from the iso3166-flags release.
    When to use:
        Once per fetch, before copying ISO 3166-2 SVGs into the static flag folder.
    What to expect:
        The release zip bytes. Retries once without certificate verification when the local store rejects GitHub.
    Exceptions:
        ``urllib.error.URLError`` when both attempts fail.
    """

    LOGGER.debug("GET %s", _RELEASE_ZIP)
    request = urllib.request.Request(_RELEASE_ZIP, headers={"User-Agent": _USER_AGENT, "Accept": "application/zip"})
    for context in (_SSL_CONTEXT, _SSL_CONTEXT_INSECURE):
        try:
            with urllib.request.urlopen(request, timeout=180, context=context) as response:
                return response.read()
        except urllib.error.URLError as exc:
            LOGGER.error("Release zip download failed: %s", exc)
            if context is _SSL_CONTEXT_INSECURE:
                raise
            LOGGER.info("Retrying the release zip download without certificate verification.")
    raise RuntimeError("No response for the iso3166-flags release zip.")


def _copy_subdivision_svgs(archive: zipfile.ZipFile) -> list[str]:
    """
    Why this exists:
        Keep only small ISO 3166-2 SVGs from the release, under the names the flag lookup expects.
    When to use:
        After the release zip is open.
    What to expect:
        Lowercase codes written to ``static/flags/subdivisions``. Oversized or non-SVG members are skipped.
    """

    written: list[str] = []
    for info in archive.infolist():
        name = info.filename.replace("\\", "/")
        if "/iso3166-2-flags/" not in f"/{name}" or not name.lower().endswith(".svg"):
            continue
        code = Path(name).stem.lower()
        if not _CODE_PATTERN.fullmatch(code) or info.file_size <= 0 or info.file_size > _MAX_BYTES:
            continue
        payload = archive.read(info)
        if len(payload) > _MAX_BYTES or b"<svg" not in payload[:800].lower():
            LOGGER.debug("Skipping %s; not a small SVG.", name)
            continue
        (_FLAG_DIR / f"{code}.svg").write_bytes(payload)
        written.append(code)
    LOGGER.info("Copied %d subdivision SVGs.", len(written))
    return written


def _write_allow_list(codes: list[str]) -> None:
    """
    Why this exists:
        Keep the TypeScript allow-list equal to the SVG folder.
    When to use:
        After downloads, including a run that downloaded nothing.
    What to expect:
        Overwrites ``subdivisionFlagCodes.ts``. Codes are lowercase.
    """

    LOGGER.debug("Writing allow-list with %d codes.", len(codes))
    lines = [
        "/**",
        " * Subdivision flag codes that have an SVG in `static/flags/subdivisions/`.",
        " *",
        " * Purpose: Lets the flag lookup use a subdivision SVG only when the file shipped.",
        " * When to use: From the origin-area flag lookup. Regenerated by `scripts/fetch-subdivision-flags.py`.",
        " * Expected outcome: One lowercase ISO 3166-2 code per SVG. An empty set means every origin uses a national flag.",
        " * Exceptions: None.",
        " */",
        "export const SUBDIVISION_FLAG_CODES: ReadonlySet<string> = new Set([",
    ]
    for code in codes:
        lines.append(f"  '{code}',")
    lines.append("]);")
    lines.append("")
    _ALLOW_LIST.write_text("\n".join(lines), encoding="utf-8")


def _write_attribution(rows: list[tuple[str, str, str, str]]) -> None:
    """
    Why this exists:
        Record the Commons source of each subdivision flag.
    When to use:
        After a fetch, merging rows for files that were already present.
    What to expect:
        One markdown line per code: code, title, license, author.
    """

    LOGGER.debug("Writing attribution for %d flags.", len(rows))
    body = ["# Subdivision flag attribution", ""]
    body.append("Each line is the lowercase ISO 3166-2 code, the file name, the license, and the source.")
    body.append("")
    for code, title, license_name, author in rows:
        body.append(f"- `{code}` — {title} — {license_name} — {author}")
    body.append("")
    _ATTRIBUTION.write_text("\n".join(body), encoding="utf-8")


def _existing_attribution() -> dict[str, tuple[str, str, str]]:
    """
    Why this exists:
        Keep attribution for SVGs this run did not download again.
    When to use:
        Before rewriting ATTRIBUTION.md.
    What to expect:
        A map of code to title, license, and author. A missing file returns an empty map.
    """

    if not _ATTRIBUTION.is_file():
        return {}
    found: dict[str, tuple[str, str, str]] = {}
    for line in _ATTRIBUTION.read_text(encoding="utf-8").splitlines():
        if not line.startswith("- `"):
            continue
        parts = [part.strip() for part in line.removeprefix("- ").split(" — ")]
        if len(parts) < 4:
            continue
        code = parts[0].strip("`")
        found[code] = (parts[1], parts[2], parts[3])
    return found


def main() -> int:
    """
    Why this exists:
        Fetch subdivision flags and regenerate the allow-list.
    When to use:
        When origin-area flags should be refreshed. Safe to repeat.
    What to expect:
        Returns 0 after the release zip is copied. Returns 1 when the zip cannot be downloaded.
    """

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    LOGGER.debug("fetch-subdivision-flags starting.")
    _FLAG_DIR.mkdir(parents=True, exist_ok=True)
    try:
        payload = _download_release_zip()
        archive = zipfile.ZipFile(io.BytesIO(payload))
    except (urllib.error.URLError, TimeoutError, zipfile.BadZipFile) as exc:
        LOGGER.error("iso3166-flags download failed.", exc_info=True)
        print(exc)
        return 1
    with archive:
        copied = set(_copy_subdivision_svgs(archive))
    previous = _existing_attribution()
    rows: list[tuple[str, str, str, str]] = []
    for path in sorted(_FLAG_DIR.glob("*.svg")):
        code = path.stem
        if code in copied or code not in previous:
            rows.append((code, f"{code}.svg", "MIT", _SOURCE_LABEL))
        else:
            title, license_name, author = previous[code]
            rows.append((code, title, license_name, author))
    _write_attribution(rows)
    _write_allow_list([row[0] for row in rows])
    LOGGER.info("Subdivision flags on disk: %d. Copied from iso3166-flags this run: %d.", len(rows), len(copied))
    return 0


if __name__ == "__main__":
    sys.exit(main())
